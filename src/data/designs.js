export const designsByCategory = Object.fromEntries(
  Object.entries(designsByCategoryData).map(([category, designs]) => [
    category,
    designs.map((design) => ({
      ...design,
      src: assetPath(design.src),
      previews: design.previews?.map((preview) => ({
        ...preview,
        src: assetPath(preview.src),
      })),
    })),
  ])
);

// Función para obtener todos los diseños de una categoría
export const getDesignsByCategory = (category) => {
  return designsByCategory[category] || [];
};

// Función para obtener un diseño específico
export const getDesignById = (id) => {
  for (const category in designsByCategory) {
    const design = designsByCategory[category].find((d) => d.id === id);
    if (design) return design;
  }
  return null;
};

// Función para obtener diseños destacados
export const getFeaturedDesigns = () => {
  const featured = [];
  for (const category in designsByCategory) {
    featured.push(
      ...designsByCategory[category].filter((d) => d.featured).slice(0, 2)
    );
  }
  return featured.slice(0, 8);
};

// Función para obtener un grupo específico
export const getDesignGroup = (category, group) => {
  const designs = designsByCategory[category] || [];
  return designs.filter((d) => d.group === group);
};

// Función para obtener el total de grupos
export const getTotalGroups = (category) => {
  const designs = designsByCategory[category] || [];
  return Math.max(...designs.map((d) => d.group), 1);
};

// Función para obtener diseños por subcategoría
export const getDesignsBySubcategory = (category, subcategory) => {
  const designs = designsByCategory[category] || [];
  return designs.filter((d) => d.subcategory === subcategory);
};
